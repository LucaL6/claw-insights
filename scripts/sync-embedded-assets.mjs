#!/usr/bin/env node
// Reads source SVGs and generates embedded-assets.ts with base64 data URI constants.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const sources = {
  ICON_DARK: resolve(root, 'packages/web/public/logo/icon-dark.svg'),
  ICON_LIGHT: resolve(root, 'packages/web/public/logo/icon-light.svg'),
  LOBSTER: resolve(root, 'packages/server/assets/openclaw-lobster.svg'),
};

function toDataUri(filePath) {
  const svg = readFileSync(filePath, 'utf8');
  return `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
}

const lines = [
  '// Auto-generated by scripts/sync-embedded-assets.mjs — do not edit manually.',
  '',
  "export type BrandTheme = 'dark' | 'light';",
  '',
];

for (const [name, path] of Object.entries(sources)) {
  const uri = toDataUri(path);
  lines.push(`export const ${name}_DATA_URI =`);
  lines.push(`  '${uri}';`);
  lines.push('');
}

lines.push(
  `export function getFooterLogoDataUri(theme: BrandTheme): string {`,
  `  return theme === 'dark' ? ICON_DARK_DATA_URI : ICON_LIGHT_DATA_URI;`,
  `}`,
  '',
  `export function getLobsterLogoDataUri(): string {`,
  `  return LOBSTER_DATA_URI;`,
  `}`,
  '',
);

const outPath = resolve(root, 'packages/server/src/renderer/markup/embedded-assets.ts');
writeFileSync(outPath, lines.join('\n'));
console.log(`✅ Generated ${outPath}`);
